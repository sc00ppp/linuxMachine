/** Meridians every 30°, sampled in latitude. */
export const MERIDIANS: ReadonlyArray<Ring> = Array.from({ length: 12 }, (_, i) => {
  const lng = -180 + i * 30;
  return Array.from({ length: 37 }, (_, j) => [lng, -90 + j * 5] as const);
});

/** Parallels every 30°, sampled in longitude. */
export const PARALLELS: ReadonlyArray<Ring> = [-60, -30, 0, 30, 60].map((lat) =>
  Array.from({ length: 73 }, (_, j) => [-180 + j * 5, lat] as const),
);
